[CmdletBinding()]
param(
  [string]$RepositoryRoot
)

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
  $scriptRoot = if ([string]::IsNullOrWhiteSpace($PSScriptRoot)) { (Get-Location).Path } else { $PSScriptRoot }
  $RepositoryRoot = (Resolve-Path (Join-Path $scriptRoot "..")).Path
}

$utf8 = [System.Text.UTF8Encoding]::new($false)
[Console]::OutputEncoding = $utf8
$OutputEncoding = $utf8

function Test-File {
  param(
    [string]$Path
  )

  return Test-Path -LiteralPath (Join-Path $RepositoryRoot $Path) -PathType Leaf
}

function Test-AnyFile {
  param(
    [string]$Directory,
    [string]$Filter
  )

  return @(Get-ChildItem -LiteralPath (Join-Path $RepositoryRoot $Directory) -Filter $Filter -ErrorAction SilentlyContinue).Count -gt 0
}

function Test-Directory {
  param(
    [string]$Path
  )

  return Test-Path -LiteralPath (Join-Path $RepositoryRoot $Path) -PathType Container
}

function New-ChecklistItem {
  param(
    [string]$Category,
    [string]$Name,
    [bool]$Ready,
    [string]$Evidence,
    [string]$Notes
  )

  return [pscustomobject]@{
    category = $Category
    name = $Name
    ready = $Ready
    evidence = $Evidence
    notes = $Notes
  }
}

