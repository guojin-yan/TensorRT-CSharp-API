$manifestPath = Join-Path $RepositoryRoot "pack\runtime\runtime-packages.manifest.json"
$manifest = Get-Content -LiteralPath $manifestPath -Raw -Encoding utf8 | ConvertFrom-Json
$localValidated = @($manifest.packages | Where-Object { $_.validationState -eq "local-validated" }).Count
$pendingLocalValidation = @($manifest.packages | Where-Object { $_.validationState -eq "pending-local-validation" }).Count
$dryRunOnly = @($manifest.packages | Where-Object { $_.validationState -eq "dry-run-only" }).Count
$knownValidationStates = @("local-validated", "pending-local-validation", "dry-run-only")
$unknownValidationStates = @(
  $manifest.packages |
    Where-Object { $knownValidationStates -notcontains $_.validationState } |
    Select-Object -ExpandProperty validationState -Unique
)
$unknownStateNotes = if ($unknownValidationStates.Count -gt 0) {
  " Unknown validation state(s): $($unknownValidationStates -join ', ')."
} else {
  ""
}
$validationStateNotes = "$localValidated local-validated package(s), $pendingLocalValidation pending-local-validation package(s), $dryRunOnly dry-run-only package(s).$unknownStateNotes"
$items.Add((New-ChecklistItem -Category "runtime" -Name "Runtime validation state matrix" -Ready ($localValidated -ge 4 -and $dryRunOnly -ge 4 -and $unknownValidationStates.Count -eq 0) -Evidence "pack/runtime/runtime-packages.manifest.json" -Notes $validationStateNotes))

$outputRoot = Join-Path $RepositoryRoot "artifacts\release-candidate"
New-Item -ItemType Directory -Path $outputRoot -Force | Out-Null

$jsonPath = Join-Path $outputRoot "release-candidate-checklist.json"
$items | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $jsonPath -Encoding utf8

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# Release Candidate Checklist")
$lines.Add("")
$lines.Add("Generated on: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
$lines.Add("")
$lines.Add("| Category | Check | Status | Evidence | Notes |")
$lines.Add("| --- | --- | --- | --- | --- |")
foreach ($item in $items) {
  $status = if ($item.ready) { "ready" } else { "pending" }
  $evidence = '`' + $item.evidence + '`'
  $lines.Add("| $($item.category) | $($item.name) | $status | $evidence | $($item.notes) |")
}

$lines.Add("")
$lines.Add("## Release Gate Interpretation")
$lines.Add("")
$lines.Add('- `ready` means the expected local artifact or report exists.')
$lines.Add('- `pending` means the release candidate needs another local or self-hosted runner pass before publication.')
$lines.Add('- Linux runtime packages must remain non-public until a real Linux self-hosted runner changes their validation state from `dry-run-only`.')
$lines.Add("- Large CUDA/cuDNN/TensorRT component packages should stay on GitHub Packages or GitHub Releases unless their size and redistribution terms are cleared for nuget.org.")
$lines.Add("- Hosted GitHub gates validate source, docs, managed packaging, and static workflow contracts; runtime package readiness requires local or self-hosted runtime artifacts.")

$markdownPath = Join-Path $outputRoot "release-candidate-checklist.md"
$lines | Set-Content -LiteralPath $markdownPath -Encoding utf8

Write-Host "Release candidate checklist written to $jsonPath"
